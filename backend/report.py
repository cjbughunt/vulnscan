"""Report rendering: JSON summary and a self-contained HTML report."""
import html
from collections import Counter

SEV_ORDER = ["critical", "high", "medium", "low", "info"]
SEV_COLOR = {
    "critical": "#7c1d1d", "high": "#b91c1c", "medium": "#c2740c",
    "low": "#2563eb", "info": "#475569",
}


def _counts(findings):
    c = Counter(f["severity"] for f in findings)
    return {s: c.get(s, 0) for s in SEV_ORDER}


def finding_key(f):
    """Stable identity for matching a finding across scans of the same target."""
    return (f.get("title") or "", f.get("location") or "")


def build_diff(current, previous):
    """Compare two finding lists; return new / fixed / unchanged breakdown."""
    prev_keys = {finding_key(f) for f in previous}
    cur_keys = {finding_key(f) for f in current}
    new = [f for f in current if finding_key(f) not in prev_keys]
    fixed = [f for f in previous if finding_key(f) not in cur_keys]
    unchanged = len(cur_keys & prev_keys)
    return {
        "new": new,
        "fixed": fixed,
        "unchanged": unchanged,
        "counts": {"new": len(new), "fixed": len(fixed), "unchanged": unchanged},
    }


def build_report_dict(scan, findings):
    return {
        "scan": {
            "id": scan["id"], "target": scan["target"], "host": scan["host"],
            "status": scan["status"], "authorized_by": scan["authorized_by"],
            "started_at": scan["started_at"], "finished_at": scan["finished_at"],
        },
        "summary": _counts(findings),
        "total": len(findings),
        "findings": findings,
    }


def render_html_report(scan, findings) -> str:
    counts = _counts(findings)
    pills = "".join(
        f'<span class="pill" style="background:{SEV_COLOR[s]}">{s.upper()}: {counts[s]}</span>'
        for s in SEV_ORDER
    )
    rows = []
    for f in findings:
        sev = f["severity"]
        rows.append(f"""
        <div class="finding sev-{sev}">
          <div class="fhead">
            <span class="badge" style="background:{SEV_COLOR.get(sev, '#475569')}">{sev.upper()}</span>
            <h3>{html.escape(f['title'])}</h3>
            <span class="src">{html.escape(f.get('source') or '')}</span>
          </div>
          <div class="meta">{html.escape(f.get('category') or '')} &middot;
            <a href="{html.escape(f.get('location') or '#')}">{html.escape(f.get('location') or '')}</a></div>
          <p>{html.escape(f.get('description') or '')}</p>
          {_block('Evidence', f.get('evidence'))}
          {_block('Remediation', f.get('remediation'))}
        </div>""")

    return f"""<!doctype html><html><head><meta charset="utf-8">
<title>VulnScan Report — {html.escape(scan['target'])}</title>
<style>
 body{{font-family:system-ui,Segoe UI,Arial,sans-serif;margin:0;background:#0f172a;color:#e2e8f0}}
 .wrap{{max-width:980px;margin:0 auto;padding:32px 20px}}
 h1{{font-size:22px;margin:0 0 4px}} .sub{{color:#94a3b8;margin-bottom:16px}}
 .pill{{display:inline-block;color:#fff;border-radius:999px;padding:4px 12px;margin:4px 6px 4px 0;font-size:13px;font-weight:600}}
 .finding{{background:#1e293b;border-radius:10px;padding:16px;margin:14px 0;border-left:5px solid #475569}}
 .sev-critical{{border-color:#7c1d1d}} .sev-high{{border-color:#b91c1c}} .sev-medium{{border-color:#c2740c}}
 .sev-low{{border-color:#2563eb}} .sev-info{{border-color:#475569}}
 .fhead{{display:flex;align-items:center;gap:10px}} .fhead h3{{margin:0;font-size:16px;flex:1}}
 .badge{{color:#fff;border-radius:6px;padding:2px 8px;font-size:11px;font-weight:700}}
 .src{{color:#64748b;font-size:12px}} .meta{{color:#94a3b8;font-size:13px;margin:6px 0}}
 .meta a{{color:#60a5fa;text-decoration:none;word-break:break-all}}
 pre{{background:#0b1220;padding:10px;border-radius:6px;overflow:auto;font-size:12px;white-space:pre-wrap;word-break:break-word}}
 .lbl{{font-size:12px;text-transform:uppercase;color:#94a3b8;margin-top:8px}}
</style></head><body><div class="wrap">
 <h1>VulnScan Report</h1>
 <div class="sub">{html.escape(scan['target'])} &middot; status: {scan['status']} &middot;
   authorized by: {html.escape(scan.get('authorized_by') or 'operator')} &middot;
   finished: {scan.get('finished_at') or '—'}</div>
 <div>{pills}</div>
 <h2>{len(findings)} findings</h2>
 {''.join(rows) or '<p>No findings.</p>'}
 <p class="sub" style="margin-top:24px">Generated by VulnScan. For authorized security testing only.</p>
</div></body></html>"""


def _block(label, value):
    if not value:
        return ""
    return f'<div class="lbl">{label}</div><pre>{html.escape(str(value))}</pre>'
